#!/usr/bin/env node
// Uploads the real company photos listed in manifest.json to Sanity and records
// the resulting asset documents in assets.json, which the migration
// (scripts/migrate/content/page-sections.mjs) reads. Safe to re-run: Sanity
// dedupes uploads by content hash, so the same file always gets the same asset id.
//
//   SANITY_WRITE_TOKEN=... NODE_USE_ENV_PROXY=1 node migration/brand-photos/upload.mjs
//
// Photos in `existing` are already Sanity assets (service and post images); they
// are looked up by id on the public API and never re-uploaded. The owner's photo
// library (library.json: files already re-encoded in library/) is uploaded as is.
//
// The token is read from the environment and never printed.

import {readFile, writeFile, copyFile} from 'node:fs/promises'
import {existsSync} from 'node:fs'
import {createHash} from 'node:crypto'

const ROOT = new URL('../../', import.meta.url)
const DIR = new URL('./', import.meta.url)
const PROJECT = 'qhi2uf0l'
const DATASET = 'production'
const API = `https://${PROJECT}.api.sanity.io/v2025-02-19`
const MIME = {avif: 'image/avif', png: 'image/png', jpg: 'image/jpeg', jpeg: 'image/jpeg', webp: 'image/webp'}

const token = process.env.SANITY_WRITE_TOKEN
if (!token) {
  console.error('SANITY_WRITE_TOKEN is not set')
  process.exit(1)
}

const manifest = JSON.parse(await readFile(new URL('manifest.json', DIR), 'utf8'))
const sha1 = (buf) => createHash('sha1').update(buf).digest('hex')

// Keep the asset document as Sanity returns it, minus revision bookkeeping, so the
// NDJSON import replaces it with identical content.
const keepAssetDoc = ({_rev, _updatedAt, ...doc}) => doc

const entry = (doc, extra) => ({
  ...extra,
  assetId: doc._id,
  url: doc.url,
  width: doc.metadata?.dimensions?.width,
  height: doc.metadata?.dimensions?.height,
  document: keepAssetDoc(doc),
})

const upload = async (file, bytes) => {
  const ext = file.split('.').pop().toLowerCase()
  const name = file.split('/').pop()
  const res = await fetch(`${API}/assets/images/${DATASET}?filename=${encodeURIComponent(name)}`, {
    method: 'POST',
    headers: {Authorization: `Bearer ${token}`, 'Content-Type': MIME[ext]},
    body: bytes,
  })
  if (!res.ok) throw new Error(`Upload of ${file} failed: ${res.status} ${await res.text()}`)
  const {document} = await res.json()
  if (document.sha1hash !== sha1(bytes)) throw new Error(`${file}: Sanity returned a different hash`)
  return document
}

const photos = []
for (const photo of manifest.photos) {
  const source = new URL(photo.source, ROOT)
  const target = new URL(photo.file, DIR)
  // the committed copy stands in once the source (the Webflow export) is gone
  const bytes = await readFile(existsSync(source) ? source : target)
  if (!existsSync(target) || sha1(await readFile(target)) !== sha1(bytes)) await copyFile(source, target)
  const document = await upload(photo.file, bytes)
  photos.push(entry(document, {file: photo.file, source: photo.source, alt: photo.alt, intendedUse: photo.intendedUse}))
  console.log(`${photo.file} → ${document._id}`)
}

const existing = []
for (const item of manifest.existing) {
  const query = encodeURIComponent(`*[_id == $id][0]`)
  const res = await fetch(`${API}/data/query/${DATASET}?query=${query}&%24id=${encodeURIComponent(JSON.stringify(item.assetId))}`)
  if (!res.ok) throw new Error(`Lookup of ${item.assetId} failed: ${res.status}`)
  const {result} = await res.json()
  if (!result) throw new Error(`${item.assetId} (${item.sourceDoc}) is not in the dataset`)
  existing.push(entry(result, {file: null, source: `Existing Sanity asset: ${item.sourceDoc}`, alt: item.alt, intendedUse: item.intendedUse}))
  console.log(`existing ${item.assetId} ok`)
}

const library = []
const libraryList = JSON.parse(await readFile(new URL('library.json', DIR), 'utf8'))
for (const photo of libraryList.photos) {
  const document = await upload(photo.file, await readFile(new URL(photo.file, DIR)))
  library.push(entry(document, {key: photo.key, file: photo.file, alt: photo.alt}))
  console.log(`${photo.file} → ${document._id}`)
}

const out = {
  about: 'Generated by upload.mjs from manifest.json. `document` is the Sanity asset document; the migration adds it to the NDJSON so references resolve locally and the import replaces it with identical content.',
  project: PROJECT,
  dataset: DATASET,
  photos,
  existing,
  library,
}
await writeFile(new URL('assets.json', DIR), JSON.stringify(out, null, 2) + '\n')
console.log(`Wrote assets.json: ${photos.length} uploaded, ${existing.length} existing, ${library.length} from the library`)
